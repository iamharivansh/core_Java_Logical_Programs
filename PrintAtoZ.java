public class PrintAtoZ {
	
	public static void main(String[] args) {
		
		
		
		for(char ch =65; ch<=90 ; ch++) {
			System.out.println((ch));
		}
		
		
		// or we can use 
		
		/*
		 * char ch ='A'; for(int i =65; i<=90 ; i++) { System.out.println((ch++)); }
		 */
		
		
		
	}

}
